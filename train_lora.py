import logging
from datasets import load_dataset
from transformers import AutoModelForCausalLM, AutoTokenizer, TrainingArguments
from trl import SFTTrainer
from peft import LoraConfig, get_peft_model

logging.basicConfig(level=logging.INFO, format="%(message)s")
log = logging.getLogger("fable.training")

def train():
    log.info("⚙️ [Distiller] Booting CPU-optimized LoRA fine-tuning...")
    
    # Load your local target model (e.g., Qwen or LLaMA)
    model_name = "Qwen/Qwen2.5-1.5B-Instruct" 
    
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(
        model_name, 
        device_map="cpu", # Forces execution on your i5 processor
        torch_dtype="auto"
    )

    # Configure Low-Rank Adaptation (LoRA) to only train 1% of the weights
    lora_config = LoraConfig(
        r=8, 
        lora_alpha=16, 
        target_modules=["q_proj", "v_proj"], 
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM"
    )
    model = get_peft_model(model, lora_config)

    # Load the Golden Records generated by Fable
    dataset = load_dataset("json", data_files="distillation_dataset.jsonl", split="train")

    def format_prompt(example):
        messages = example["messages"]
        return tokenizer.apply_chat_template(messages, tokenize=False)

    # CPU-Optimized Training Arguments
    training_args = TrainingArguments(
        output_dir="./fable_evolved_weights",
        per_device_train_batch_size=1,
        gradient_accumulation_steps=4,
        num_train_epochs=1,
        learning_rate=2e-4,
        logging_steps=5,
        save_strategy="no",
        use_cpu=True # Critical for your hardware
    )

    trainer = SFTTrainer(
        model=model,
        train_dataset=dataset,
        formatting_func=format_prompt,
        args=training_args,
    )

    log.info("🚀 [Distiller] Beginning weight distillation. This will take time on a CPU...")
    trainer.train()
    
    trainer.model.save_pretrained("./fable_evolved_weights_final")
    log.info("✅ [Distiller] Evolution complete. New weights saved to ./fable_evolved_weights_final")

if __name__ == "__main__":
    train()
